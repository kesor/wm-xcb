#!/usr/bin/env bash
#
# check-sanitize-x.sh - run the WM in a nested X server under ASan and UBSan.
#
# Usage: scripts/check-sanitize-x.sh [--update-baseline] [--verbose]
#
# scripts/check-sanitize.sh runs the unit suite under the sanitizers, and that
# suite has no X connection: the component code that talks to X returns early
# when there is no display, so the unit run never builds a request. Anything
# wrong with a request therefore cannot appear there. Mapping a window read 4
# bytes out of a 2-byte border width, survived the whole unit suite and every
# other gate, and aborted on the first MapRequest under ASan.
#
# So this gate starts a real WM against a nested server with
# scripts/xephyr-test.sh and fails on three things: the harness failing (the WM
# died, a window was never mapped, windows do not tile), an ASan error in the
# WM log, and a leak site or UBSan report in that log that is not listed in
# tests/quality/sanitize-x-baseline.txt.
#
# Leaks are baselined rather than fatal because the harness stops the WM with a
# signal, so LeakSanitizer reports whatever was still allocated at that moment,
# startup included. A site that is not in the baseline is new, which is the
# point: the list only shrinks.
#
# Needs what the harness needs: Xephyr, xdotool, xprop, and a display for
# Xephyr to draw into. CI runs it under xvfb-run, next to the seam job.
#
# Exit status: 0 when the run is clean, 1 otherwise.

set -uo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

BASELINE="$ROOT_DIR/tests/quality/sanitize-x-baseline.txt"
UPDATE=0
VERBOSE=0
for arg in "$@"; do
  case "$arg" in
    --update-baseline) UPDATE=1 ;;
    -v | --verbose) VERBOSE=1 ;;
    -h | --help)
      awk 'NR > 1 { if (!/^#/) exit; sub(/^# ?/, ""); print }' "$0"
      exit 0
      ;;
    *)
      echo "check-sanitize-x: unknown argument '$arg'" >&2
      exit 1
      ;;
  esac
done

# The leak report is the exit-time one, so it is only complete if the harness
# lets the WM exit rather than killing it outright. detect_leaks=1 is the
# default on Linux; set it anyway so a caller's ASAN_OPTIONS cannot turn the
# leak half of this gate off by accident.
export ASAN_OPTIONS="${ASAN_OPTIONS:-detect_leaks=1}"

# The harness refuses to run without the test client, and `make clean` in CI
# removes it.
make -s tools/xclient >/dev/null || {
  echo "check-sanitize-x: cannot build tools/xclient" >&2
  exit 1
}

OUT=$(mktemp) || exit 1
trap 'rm -f "$OUT"' EXIT

echo "check-sanitize-x: running scripts/xephyr-test.sh against the SANITIZE=1 build"
SANITIZE=1 "$ROOT_DIR/scripts/xephyr-test.sh" >"$OUT" 2>&1
rc=$?
cat "$OUT"
if [ "$rc" -ne 0 ]; then
  echo "check-sanitize-x: the harness failed; the WM does not survive a sanitized run against X"
  exit 1
fi

LOG=$(sed -n 's/^xephyr-test.sh: .*log=//p' "$OUT" | head -n 1)
if [ ! -f "$LOG" ]; then
  echo "check-sanitize-x: the harness named no readable log, so the run cannot be checked" >&2
  exit 1
fi

# A fatal ASan error is never accepted: an entry in the baseline says "this
# allocation site is known", not "reading past a buffer is fine".
if grep -q 'ERROR: AddressSanitizer:' "$LOG"; then
  echo "check-sanitize-x: the WM log carries an AddressSanitizer error:"
  grep -A12 -m1 'ERROR: AddressSanitizer:' "$LOG"
  echo "check-sanitize-x: see $LOG"
  exit 1
fi

# One site per leak: the first stack frame that is a file in this repository,
# keyed by file and function. The line number is not part of the key, for the
# same reason as in check-sanitize.sh: it moves with any edit above it.
leak_sites() {
  awk -v root="$ROOT_DIR/" '
    /^(Direct|Indirect) leak of/ { pending = 1; next }
    pending && /^[ \t]*#[0-9]+/ {
      fn = ""; loc = ""
      for (i = 1; i < NF; i++) {
        if ($i == "in") { fn = $(i + 1); loc = $(i + 2); break }
      }
      sub(/:[0-9]+$/, "", loc)
      if (fn != "" && loc ~ /\.(c|h)$/ && index(loc, root) == 1) {
        print substr(loc, length(root) + 1) "|" fn
        pending = 0
      }
      next
    }
    { pending = 0 }
  ' "$1" | sort -u
}

# A UBSan report does not stop the program, so nothing else in the run would
# notice it: the message is what gets baselined, not the file.
ubsan_sites() {
  sed "s|^$ROOT_DIR/||" "$1" |
    sed -nE 's#^([^ :]+\.(c|h)):[0-9]+:[0-9]+: runtime error: (.*)$#\1|runtime error: \3#p' |
    sort -u
}

mapfile -t SITES < <({ leak_sites "$LOG"; ubsan_sites "$LOG"; } | sort -u)

if [ "${#SITES[@]}" -eq 0 ]; then
  echo "check-sanitize-x: no sanitizer report at all"
  exit 0
fi

if [ "$UPDATE" -eq 1 ]; then
  mkdir -p "$(dirname "$BASELINE")"
  {
    echo "# Sanitizer reports from a live WM in a nested X server."
    echo "#"
    echo "# Generated by scripts/check-sanitize-x.sh --update-baseline."
    echo "# A site listed here does not fail the gate; a site missing from here"
    echo "# does. Remove entries as the defects are fixed: the list is meant to"
    echo "# shrink. Leak entries are file|function, UBSan entries are"
    echo "# file|runtime error: <message>."
    printf '%s\n' "${SITES[@]}"
  } >"$BASELINE"
  echo "check-sanitize-x: baseline updated with ${#SITES[@]} site(s)"
  exit 0
fi

declare -A KNOWN=()
if [ -f "$BASELINE" ]; then
  while IFS= read -r line; do
    case "$line" in '' | '#'*) continue ;; esac
    KNOWN["$line"]=1
  done <"$BASELINE"
fi

NEW=0
declare -A SEEN=()
for site in "${SITES[@]}"; do
  SEEN["$site"]=1
  if [ -n "${KNOWN[$site]:-}" ]; then
    [ "$VERBOSE" -eq 1 ] && printf '  known  %s\n' "$site"
    continue
  fi
  NEW=$((NEW + 1))
  printf '  NEW REPORT  %s\n' "$site"
done

STALE=0
for site in "${!KNOWN[@]}"; do
  [ -z "${SEEN[$site]:-}" ] && STALE=$((STALE + 1)) && printf '  stale baseline entry: %s\n' "$site"
done

echo "check-sanitize-x: ${#SITES[@]} site(s), $NEW new"
[ "$STALE" -gt 0 ] && echo "check-sanitize-x: $STALE stale baseline entrie(s); run --update-baseline to drop them"

if [ "$NEW" -gt 0 ]; then
  echo "A new sanitizer report from a live WM: fix it, or run --update-baseline and say why it is deferred."
  echo "The WM log is $LOG"
  exit 1
fi
exit 0
