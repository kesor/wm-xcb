# shellcheck shell=bash
#
# lib/shellcheck-report.sh - judge recorded shellcheck output against a
# baseline, and refuse the shapes of output that mean the lint never ran.
#
# Sourced by scripts/check-shellcheck.sh, which runs shellcheck over the tree,
# and by tests/x/test-97-shellcheck-report.sh, which feeds recorded output in
# place of a run.
#
# The functions are named lint_*, not shellcheck_*: shellcheck reads a comment
# whose first word is "shellcheck" as a directive, so a doc comment naming the
# function it documents is a parse error in the file that defines it.
#
# A finding is keyed by <file>|<code>|<message>, with the number of occurrences
# after it. The line and column are dropped on purpose: any edit above a finding
# would otherwise invalidate its entry, and the baseline would be rewritten for
# changes that fixed nothing. The count is kept because dropping it would hide
# the second occurrence of a finding that is already known: a file with one
# SC2164 is baselined, and a file that grows a second one still fails.
#
# A gate that can be silenced answers the same as one that found nothing, so the
# two shapes that produce silence are refused here rather than in the gate:
#
#   - a log with a line in it that is not a finding. A parse failure, a changed
#     output format or a stray message is not a clean run;
#   - a baseline with entries next to a log with no finding at all. That is
#     either the findings fixed without their baseline update or a lint that
#     never ran, and the log does not say which.

# lint_report_findings <log>
#   One entry per <file>|<code>|<message>, with "|<occurrences>" appended, on
#   stdout and sorted. The input is shellcheck's gcc format:
#     file:line:col: severity: message [SCnnnn]
lint_report_findings() {
  local log=$1
  sed -nE 's#^([^:]+):[0-9]+:[0-9]+: [a-z]+: (.*) \[(SC[0-9]+)\]$#\1|\3|\2#p' "$log" |
    sort | uniq -c | sed -nE 's#^ *([0-9]+) (.*)$#\2|\1#p' | sort
}

# lint_report_lines <log>
#   Number of non-empty lines, which lint_report_findings accounts for
#   one entry at a time. The gate fails when the two disagree.
lint_report_lines() {
  grep -c . "$1" || true
}

# lint_write_baseline <baseline> <generator> [entry...]
#   Writes the baseline the gate reads, with the generator named so a reader
#   knows what to run to regenerate it.
lint_write_baseline() {
  local baseline=$1 generator=$2
  shift 2
  mkdir -p "$(dirname "$baseline")"
  {
    echo "# Shellcheck findings that are known and do not fail the gate."
    echo "#"
    echo "# Generated by $generator."
    echo "# Each line is <file>|<code>|<message>|<occurrences>. A finding listed"
    echo "# here does not fail the gate; one missing from here does, and so does"
    echo "# an extra occurrence of a listed one. Remove entries as the findings"
    echo "# are fixed: the list is meant to shrink."
    [ "$#" -eq 0 ] || printf '%s\n' "$@"
  } >"$baseline"
}

# lint_verify <log> <baseline> <gate name>
#   Returns 0 when the run is acceptable and 1 when it is not, printing why.
lint_verify() {
  local log=$1 baseline=$2 gate=$3
  local entry key count have line
  local -a findings=()
  mapfile -t findings < <(lint_report_findings "$log")

  local total=0 seen_total=0
  for entry in "${findings[@]}"; do
    seen_total=$((seen_total + ${entry##*|}))
  done
  total=$(lint_report_lines "$log")

  local -A known=()
  local known_count=0 known_total=0
  if [ -f "$baseline" ]; then
    while IFS= read -r line; do
      case "$line" in '' | '#'*) continue ;; esac
      known["${line%|*}"]=${line##*|}
      known_count=$((known_count + 1))
      known_total=$((known_total + ${line##*|}))
    done <"$baseline"
  fi

  # Line count and parsed findings have to agree, or something in the log is not
  # a finding and the run is not clean.
  if [ "$total" -ne "$seen_total" ]; then
    echo "$gate: $total line(s) of shellcheck output, $seen_total accounted for as findings"
    echo "$gate: a line that is not a finding is not a clean run. The log is $log"
    grep -vE '^[^:]+:[0-9]+:[0-9]+: [a-z]+: .* \[SC[0-9]+\]$' "$log" | head -20 | sed 's/^/  not a finding: /'
    return 1
  fi

  if [ "$seen_total" -eq 0 ]; then
    if [ "$known_total" -eq 0 ]; then
      echo "$gate: no finding at all"
      return 0
    fi
    echo "$gate: the log has no finding, but $baseline lists $known_count entry(s)."
    echo "$gate: either those findings are fixed and the baseline was not updated with them, or shellcheck did not run."
    echo "$gate: the log cannot tell the two apart, so this fails rather than guess."
    echo "$gate: if they are really gone, run --update-baseline and commit the new baseline with the fix."
    return 1
  fi

  local -A seen=()
  local new=0
  for entry in "${findings[@]}"; do
    key=${entry%|*}
    count=${entry##*|}
    seen["$key"]=$count
    have=${known[$key]:-0}
    if [ "$count" -le "$have" ]; then
      [ "${SHELLCHECK_VERBOSE:-0}" -eq 1 ] && printf '  known  %s (%s)\n' "$key" "$count"
      continue
    fi
    new=$((new + count - have))
    if [ "$have" -eq 0 ]; then
      printf '  NEW FINDING  %s (%s)\n' "$key" "$count"
    else
      printf '  NEW FINDING  %s (%s, baseline lists %s)\n' "$key" "$count" "$have"
    fi
  done

  local stale=0
  for key in "${!known[@]}"; do
    if [ -z "${seen[$key]+set}" ]; then
      stale=$((stale + 1))
      printf '  stale baseline entry: %s\n' "$key"
    elif [ "${seen[$key]}" -lt "${known[$key]}" ]; then
      stale=$((stale + 1))
      printf '  baseline entry can shrink: %s (lists %s, found %s)\n' \
        "$key" "${known[$key]}" "${seen[$key]}"
    fi
  done

  echo "$gate: $seen_total finding(s), $new new, $((seen_total - new)) known"
  if [ "$stale" -gt 0 ]; then
    echo "$gate: $stale baseline entrie(s) can be dropped or lowered; run --update-baseline"
  fi

  if [ "$new" -gt 0 ]; then
    echo "A finding the baseline does not record: fix it, or run --update-baseline and say why it is deferred."
    return 1
  fi
  return 0
}
