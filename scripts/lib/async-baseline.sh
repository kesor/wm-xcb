# shellcheck shell=bash
#
# lib/async-baseline.sh - write tests/quality/async-baseline.txt.
#
# Sourced by scripts/check-async.sh --update-baseline, which is the only writer,
# and by tests/x/test-112-baseline-refresh.sh, which regenerates both reviewed
# baselines from their own entries and compares the result with the committed
# file. The header lives here and not in the committed file, because the writer
# replaces the whole file: a line put in the baseline by hand is gone at the
# next refresh.

# async_baseline_write <baseline> [entry...]
#
# Writes the header and the entries, in the order given. A caller that wants a
# sorted file sorts before the call: the committed file is judged against this
# output line for line.
async_baseline_write() {
  local baseline=$1
  shift
  mkdir -p "$(dirname "$baseline")" || return 1
  {
    echo "# Known blocking calls in the window manager event loop."
    echo "#"
    echo "# Generated by scripts/check-async.sh --update-baseline."
    echo "# Each line is <file>|<normalized call>. A violation listed here does not"
    echo "# fail the check; a violation missing from here does. Remove entries when"
    echo "# the call is gone: the script reports stale lines, and the point of the"
    echo "# file is that it shrinks."
    [ "$#" -eq 0 ] || printf '%s\n' "$@"
  } >"$baseline"
}
