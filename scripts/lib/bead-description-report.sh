# shellcheck shell=bash
#
# lib/bead-description-report.sh - judge a list of issues for a description that
# went missing.
#
# Sourced by scripts/check-bead-descriptions.sh, which reads the list from the
# tracker, and by tests/x/test-103-bead-description-report.sh, which feeds this
# recorded JSON instead of needing a database.
#
# A description disappears without a word: `bd update <id> --description ""`
# prints "Updated issue" and exits 0, and so does `--description "$(...)"` when
# the substitution produced nothing. Nothing in that command says the text is
# gone. The gate cannot stop the command, so it catches the result at the next
# commit and names the bead.
#
# `bd update --stdin` refuses an empty body, which is why the rewrite path in
# AGENTS.md is stdin, and it accepts a body of nothing but whitespace. So the
# comparison is on the stripped text: whitespace only is a description that was
# erased with a space in it.
#
# The baseline records the empty descriptions the gate accepts as debt, so the
# writer is the one place that can turn the gate green over a wipe: an id that
# arrives with no description is the finding, not a repair, and it refuses.

# bead_description_missing <issues-json>
#   One line per issue whose description is empty, whitespace only, or null:
#   `<id>TAB<status>TAB<title>`.
bead_description_missing() {
  jq -r '.[]
    | select(((.description // "") | test("\\S")) | not)
    | [.id, (.status // "?"), (.title // "")]
    | @tsv' "$1"
}

# bead_description_write_baseline <baseline> <issues-json> <gate>
#   Drops the entries the tracker no longer needs: an id whose description is
#   back, and one the tracker does not carry. Returns 1 and writes nothing when
#   the tracker carries an issue with no description that the file does not
#   already hold, because an entry records that empty description as accepted
#   and that is the finding the gate names. Regenerating over a wipe is how the
#   command the gate prints turned the wipe green again.
bead_description_write_baseline() {
  local baseline=$1 issues=$2 gate=$3
  local -A held=() exists=() missing=()
  local id line
  if [ -f "$baseline" ]; then
    while IFS= read -r line; do
      case "$line" in '' | '#'*) continue ;; esac
      held["$line"]=1
    done <"$baseline"
  fi
  while IFS= read -r id; do
    [ -n "$id" ] && exists["$id"]=1
  done < <(jq -r '.[].id' "$issues")
  while IFS=$'\t' read -r id _; do
    [ -n "$id" ] && missing["$id"]=1
  done < <(bead_description_missing "$issues")

  local -a added=()
  for id in "${!missing[@]}"; do
    [ -n "${held[$id]:-}" ] || added+=("$id")
  done
  if [ "${#added[@]}" -gt 0 ]; then
    mapfile -t added < <(printf '%s\n' "${added[@]}" | sort)
    for id in "${added[@]}"; do
      printf '  WOULD RECORD  %s\n' "$id"
    done
    echo "$gate: ${#added[@]} issue(s) have no description and no entry."
    echo "An entry records that bead as accepted without one, which is the finding this"
    echo "gate exists to name: regenerating over it is how a wipe was turned green. The"
    echo "text before a wipe is in 'bd history <id> --events', under Old:. Write it back"
    echo "through stdin, which refuses an empty body:"
    echo "  bd update <id> --stdin <<'EOF'"
    echo "  ..."
    echo "  EOF"
    echo "An issue that never had a description needs one too: why it exists and how to"
    echo "check that it is done."
    echo "Nothing was written."
    return 1
  fi

  mkdir -p "$(dirname "$baseline")"
  {
    echo "# Beads issues with no description, which scripts/check-bead-descriptions.sh"
    echo "# accepts."
    echo "#"
    echo "# Generated by scripts/check-bead-descriptions.sh --update-baseline."
    echo "#"
    echo "# An issue listed here does not fail the gate; an issue missing from here does."
    echo "# Every issue had a description when the gate landed, so an entry can only come"
    echo "# from before that, and an empty one from now on is a description that was lost"
    echo "# or never written."
    echo "#"
    echo "# The update only drops entries: one whose description is back, and one the"
    echo "# tracker no longer carries. It refuses to add one, because an entry records an"
    echo "# empty description as accepted, which is the finding this gate names."
    for id in "${!held[@]}"; do
      [ -n "${exists[$id]:-}" ] || continue
      [ -n "${missing[$id]:-}" ] || continue
      printf '%s\n' "$id"
    done | sort
  } >"$baseline"
}

# bead_description_verify <issues-json> <baseline> <gate>
#   0 when every issue carries a description or is listed in the baseline, 1
#   when one is not, printing which and where the text went.
bead_description_verify() {
  local issues=$1 baseline=$2 gate=$3
  local total

  # A file that is not an issue list is a broken read, not a clean tracker: an
  # empty answer from a command that failed and one from a tracker with nothing
  # in it are the same bytes, and only one of them is good news.
  if ! total=$(jq -r 'if type == "array" then length else error("not an array") end' "$issues" 2>/dev/null); then
    echo "$gate: $issues is not a JSON array of issues, so nothing was read"
    return 1
  fi

  local -A known=() seen=()
  local line
  if [ -f "$baseline" ]; then
    while IFS= read -r line; do
      case "$line" in '' | '#'*) continue ;; esac
      known["$line"]=1
    done <"$baseline"
  fi

  if [ "$total" -eq 0 ]; then
    echo "$gate: the tracker answered with no issue, so there is no description to lose"
    return 0
  fi

  local -a missing=()
  mapfile -t missing < <(bead_description_missing "$issues")

  local new=0 stale=0 id status title
  for line in "${missing[@]}"; do
    IFS=$'\t' read -r id status title <<<"$line"
    seen["$id"]=1
    if [ -n "${known[$id]:-}" ]; then
      [ "${BEAD_DESCRIPTION_VERBOSE:-0}" -eq 1 ] && printf '  known  %s\n' "$id"
      continue
    fi
    new=$((new + 1))
    printf '  NO DESCRIPTION  %s (%s) %s\n' "$id" "$status" "$title"
  done

  for id in "${!known[@]}"; do
    [ -z "${seen[$id]:-}" ] && stale=$((stale + 1)) && printf '  stale baseline entry: %s\n' "$id"
  done

  if [ "$new" -eq 0 ]; then
    if [ "${#missing[@]}" -eq 0 ]; then
      echo "$gate: $total issue(s), every one with a description"
    else
      echo "$gate: $total issue(s), ${#missing[@]} without a description, all in the baseline"
    fi
    [ "$stale" -gt 0 ] && echo "$gate: $stale stale baseline entrie(s); --update-baseline drops them"
    return 0
  fi

  echo "$gate: $new issue(s) have no description."
  echo "An empty description is what 'bd update <id> --description \"\"' writes, and a"
  echo "substitution that produced nothing writes the same thing, both exiting 0."
  echo "The text before a wipe is in 'bd history <id> --events', under Old:. Write it"
  echo "back through stdin, which refuses an empty body:"
  echo "  bd update <id> --stdin <<'EOF'"
  echo "  ..."
  echo "  EOF"
  echo "A bead that never had a description needs one too: why it exists and how to"
  echo "check that it is done."
  return 1
}
