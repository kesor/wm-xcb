# shellcheck shell=bash
#
# lib/sanitize-report.sh - judge one recorded sanitizer run against a baseline,
# and keep the caller's environment out of what that run reports.
#
# Sourced by scripts/check-sanitize.sh, which runs the unit suite under the
# sanitizers, by scripts/lib/sanitize-x-report.sh, which adds the nested-server
# half, and by tests/x/test-96-sanitize-report.sh, which feeds recorded output
# in place of a run.
#
# ROOT_DIR must be set. A site is keyed by a path relative to it, because a
# frame in a library outside the repository is not a site here.
#
# A gate that can be silenced answers the same as one that found nothing, so
# two of the shapes that produce silence are refused here rather than in each
# gate:
#
#   - a suppression file, or a report redirected away from the log. Either one
#     turns a real report into silence, so sanitize_scrub_options removes those
#     keys from the caller's sanitizer options before the run starts;
#   - a baseline with entries and a log with no report: either the fixes landed
#     without the baseline update, or the sanitizer never ran. The log cannot
#     say which, so the gate does not guess.
#
# What proves the instrumented binary ran at all is gate-specific and stays
# there: the nested-server gate reads the variant line its harness prints, and
# the unit gate checks the test binary for the ASan runtime.

# sanitize_scrub_options <environment variable name>
#   Drops suppressions= and log_path= from the named sanitizer option string and
#   writes the result back. The runtime splits that string on colon, comma, and
#   whitespace, so a comma-only split leaves either key in place when another
#   key precedes it. Either key turns a real report into silence, and appending
#   detect_leaks=1 does not undo that: those two are not flags the forced suffix
#   can override. Surviving keys are rejoined with commas, which the runtime
#   accepts as a separator, so the caller can then append the keys the gate forces.
sanitize_scrub_options() {
  local name=$1 value items=() kept=() item
  value=${!name-}
  IFS=$' \t\n:,' read -r -a items <<<"$value"
  for item in "${items[@]}"; do
    case "$item" in
      '' | suppressions=* | log_path=*) continue ;;
    esac
    kept+=("$item")
  done
  if [ "${#kept[@]}" -eq 0 ]; then
    printf -v "$name" '%s' ''
  else
    local IFS=,
    printf -v "$name" '%s' "${kept[*]}"
  fi
  export "${name?}"
}

# sanitize_report_sites <log>
#   One site per leak or UBSan report, on stdout. A leak site is the first stack
#   frame that is a file in this repository, keyed by file and function: the line
#   number moves with any edit above it, and inlining changes which frame ASan
#   reports between two builds of the same source.
#
#   The location is accepted in either form gcc emits. A frame for a file named
#   with a directory (src/target/monitor.c) is reported as that relative path,
#   and one for a file named without (wm.c) is reported under the compiler's
#   working directory, so both have to key to the same site or a gate misses
#   every leak below the tree root.
sanitize_report_sites() {
  local log=$1
  {
    awk -v root="$ROOT_DIR/" '
      /^(Direct|Indirect) leak of/ { pending = 1; next }
      pending && /^[ \t]*#[0-9]+/ {
        fn = ""; loc = ""
        for (i = 1; i < NF; i++) {
          if ($i == "in") { fn = $(i + 1); loc = $(i + 2); break }
        }
        sub(/(:[0-9]+)+$/, "", loc)
        if (index(loc, root) == 1) loc = substr(loc, length(root) + 1)
        if (fn != "" && loc !~ /^\// && loc ~ /^[A-Za-z0-9_.\/-]+\.(c|h)$/) {
          print loc "|" fn
          pending = 0
        }
        next
      }
      { pending = 0 }
    ' "$log"
    # UBSan does not stop the program, so nothing else in the run would notice
    # it: the message is what gets baselined, not the file.
    sed "s|^$ROOT_DIR/||" "$log" |
      sed -nE 's#^([^ :]+\.(c|h)):[0-9]+:[0-9]+: runtime error: (.*)$#\1|runtime error: \3#p'
  } | sort -u
}

# sanitize_write_baseline <baseline> <generator> [site...]
#   Writes the baseline both gates read, with the generator named so a reader
#   knows which command to run to regenerate it.
sanitize_write_baseline() {
  local baseline=$1 generator=$2
  shift 2
  mkdir -p "$(dirname "$baseline")"
  {
    echo "# Sanitizer reports that are known and do not fail the gate."
    echo "#"
    echo "# Generated by $generator."
    echo "# A site listed here does not fail the gate; a site missing from here"
    echo "# does. Remove entries as the defects are fixed: the list is meant to"
    echo "# shrink. Leak entries are file|function, UBSan entries are"
    echo "# file|runtime error: <message>."
    [ "$#" -eq 0 ] || printf '%s\n' "$@"
  } >"$baseline"
}

# sanitize_verify_sites <log> <baseline> <gate name>
#   Returns 0 when the run is acceptable and 1 when it is not, printing why.
sanitize_verify_sites() {
  local log=$1 baseline=$2 gate=$3
  local line site
  local -a sites=()
  mapfile -t sites < <(sanitize_report_sites "$log")

  local -A known=() seen=()
  local known_count=0
  if [ -f "$baseline" ]; then
    while IFS= read -r line; do
      case "$line" in '' | '#'*) continue ;; esac
      known["$line"]=1
      known_count=$((known_count + 1))
    done <"$baseline"
  fi

  if [ "${#sites[@]}" -eq 0 ]; then
    if [ "$known_count" -eq 0 ]; then
      echo "$gate: no sanitizer report at all"
      return 0
    fi
    echo "$gate: the log carries no sanitizer report, but $baseline lists $known_count site(s)."
    echo "$gate: either those sites are fixed and the baseline was not updated with them, or the sanitizer did not run."
    echo "$gate: the log cannot tell the two apart, so this fails rather than guess."
    echo "$gate: if the reports are really gone, run --update-baseline and commit the new baseline with the fix."
    return 1
  fi

  local new=0 stale=0
  for site in "${sites[@]}"; do
    seen["$site"]=1
    if [ -n "${known[$site]:-}" ]; then
      [ "${SANITIZE_VERBOSE:-0}" -eq 1 ] && printf '  known  %s\n' "$site"
      continue
    fi
    new=$((new + 1))
    printf '  NEW REPORT  %s\n' "$site"
  done

  for site in "${!known[@]}"; do
    [ -z "${seen[$site]:-}" ] && stale=$((stale + 1)) && printf '  stale baseline entry: %s\n' "$site"
  done

  echo "$gate: ${#sites[@]} site(s), $new new"
  [ "$stale" -gt 0 ] && echo "$gate: $stale stale baseline entrie(s); run --update-baseline to drop them"

  if [ "$new" -gt 0 ]; then
    echo "A new sanitizer report: fix it, or run --update-baseline and say why it is deferred."
    echo "The log is $log"
    return 1
  fi
  return 0
}
