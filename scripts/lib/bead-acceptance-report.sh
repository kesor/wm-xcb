# shellcheck shell=bash
#
# lib/bead-acceptance-report.sh - judge a list of issues for acceptance criteria
# that went missing, and for issues that never had any.
#
# Sourced by scripts/check-bead-acceptance.sh, which reads the list from the
# tracker, and by tests/x/test-110-bead-acceptance-report.sh, which feeds this
# recorded JSON instead of needing a database.
#
# It answers two questions, and each has a baseline of its own because they are
# not the same question. `bead_acceptance_verify` asks whether a bead that had
# criteria still has them, and tests/quality/bead-acceptance-baseline.txt is the
# record of which did. `bead_acceptance_verify_missing` asks whether a live bead
# has any at all, and tests/quality/bead-acceptance-missing-baseline.txt is the
# debt that existed when that question started being asked.
#
# `bd update <id> --acceptance ""` prints "Updated issue" and exits 0, and so
# does `--acceptance "$(...)"` when the substitution produced nothing. Unlike
# --description there is no stdin form for --acceptance, so nothing in bd
# refuses an empty value and the field is erased with a success message.
#
# bd also omits the key when the text is empty, which is why the check is
# baseline-relative: an issue whose acceptance criteria were wiped and one that
# never had any are the same bytes in the tracker output. The baseline records
# the ids whose criteria are meant to be there, so a wipe is visible against
# that record and nowhere else.

# bead_acceptance_with_text <issues-json>
#   One line per issue whose acceptance criteria carry text:
#   `<id>TAB<status>TAB<title>`.
bead_acceptance_with_text() {
  jq -r '.[]
    | select(((.acceptance_criteria // "") | test("\\S")))
    | [.id, (.status // "?"), ((.title // "") | gsub("[\\t\\n]"; " "))]
    | @tsv' "$1"
}

# bead_acceptance_without_text <issues-json>
#   The same row for every issue that is still live and whose criteria carry no
#   text, where live is anything but closed: the criteria a closed bead never
#   had are history, and a commit that has work to make is not the place to
#   argue with history.
bead_acceptance_without_text() {
  jq -r '.[]
    | select((.status // "open") != "closed")
    | select(((.acceptance_criteria // "") | test("\\S")) | not)
    | [.id, (.status // "?"), ((.title // "") | gsub("[\\t\\n]"; " "))]
    | @tsv' "$1"
}

# bead_acceptance_write_baseline <baseline> <issues-json>
#   Records every issue that has acceptance text now. The list is not debt the
#   way the description baseline is: a bead missing from it is simply not
#   checked, so run the update when a bead gains criteria.
bead_acceptance_write_baseline() {
  local baseline=$1 issues=$2
  mkdir -p "$(dirname "$baseline")"
  {
    echo "# Beads issues whose acceptance criteria the check protects."
    echo "#"
    echo "# Generated by scripts/check-bead-acceptance.sh --update-baseline."
    echo "#"
    echo "# An issue listed here fails the gate when its acceptance criteria are"
    echo "# gone, when they are whitespace only, or when the issue is missing from"
    echo "# the list the gate read. An issue missing from here is not checked."
    echo "# bd omits the field when it is empty, so a wipe and a bead that never"
    echo "# had acceptance criteria are the same output; this list is the record of"
    echo "# which is which. Regenerate it after a bead gains acceptance criteria."
    bead_acceptance_with_text "$issues" | cut -f1
  } >"$baseline"
}

# bead_acceptance_write_missing_baseline <baseline> <issues-json>
#   Records every live issue that carries no acceptance criteria now. bd writes
#   no key for the empty field, so an issue whose criteria were never written
#   and one that lost them are the same output: without this list the first
#   shape is invisible, and the worker plans a bead whose only record of done is
#   its description.
bead_acceptance_write_missing_baseline() {
  local baseline=$1 issues=$2
  mkdir -p "$(dirname "$baseline")"
  {
    echo "# Beads issues with no acceptance criteria, which the check accepts."
    echo "#"
    echo "# Generated by scripts/check-bead-acceptance.sh --update-baseline."
    echo "#"
    echo "# An issue missing from here that carries no criteria fails the gate."
    echo "# An entry does not fail it. Remove an entry once the criteria exist:"
    echo "# the list is meant to shrink, and a stale entry says a bead has none"
    echo "# when it has text."
    bead_acceptance_without_text "$issues" | cut -f1
  } >"$baseline"
}

# bead_acceptance_verify <issues-json> <baseline> <gate>
#   0 when every issue the baseline lists still carries its acceptance text, 1
#   when one lost it or is missing from the list, printing which and why.
bead_acceptance_verify() {
  local issues=$1 baseline=$2 gate=$3
  local total

  # A file that is not an issue list is a broken read, not a tracker with
  # nothing in it. The one case this must not swallow is a null acceptance
  # value: that is a verdict, not a parse error, and it is reported below.
  if ! total=$(jq -r 'if type == "array" then length else error("not an array") end' "$issues" 2>/dev/null); then
    echo "$gate: $issues is not a JSON array of issues, so nothing was read"
    return 1
  fi

  local -A known=()
  local known_count=0 line
  if [ -f "$baseline" ]; then
    while IFS= read -r line; do
      case "$line" in '' | '#'*) continue ;; esac
      known["$line"]=1
      known_count=$((known_count + 1))
    done <"$baseline"
  fi

  # One row per issue for the report to name it by, plus the set that carries
  # text. `bead_acceptance_with_text` is the only place the question "is this
  # field filled?" is decided, so --update-baseline records exactly what the
  # gate protects and the two cannot drift apart.
  local -A status_of=() title_of=() intact_of=()
  local id status title
  while IFS=$'\t' read -r id status title; do
    [ -n "$id" ] || continue
    status_of["$id"]=$status
    title_of["$id"]=$title
  done < <(jq -r '.[]
    | [.id, (.status // "?"), ((.title // "") | gsub("[\\t\\n]"; " "))]
    | @tsv' "$issues")

  local text_count=0
  while IFS=$'\t' read -r id status title; do
    [ -n "$id" ] || continue
    intact_of["$id"]=1
    text_count=$((text_count + 1))
  done < <(bead_acceptance_with_text "$issues")

  local -a lost=() absent=()
  for id in "${!known[@]}"; do
    if [ -z "${status_of[$id]:-}" ]; then
      absent+=("$id")
    elif [ -z "${intact_of[$id]:-}" ]; then
      lost+=("$id")
    elif [ "${BEAD_ACCEPTANCE_VERBOSE:-0}" -eq 1 ]; then
      printf '  kept   %s\n' "$id"
    fi
  done
  if [ "${#lost[@]}" -gt 0 ]; then
    mapfile -t lost < <(printf '%s\n' "${lost[@]}" | sort)
  fi
  if [ "${#absent[@]}" -gt 0 ]; then
    mapfile -t absent < <(printf '%s\n' "${absent[@]}" | sort)
  fi

  local unlisted=0
  for id in "${!intact_of[@]}"; do
    [ -n "${known[$id]:-}" ] || unlisted=$((unlisted + 1))
  done

  # A bead created during a cycle - by the worker or by the review - is
  # unlisted, and "run --update-baseline" is read as "a second commit" by a
  # reviewer who is one command from done. The baseline is a tracked file, so
  # naming it says the update fits in the commit already being made.
  local hint=""
  if [ "$unlisted" -gt 0 ]; then
    hint="$gate: $unlisted issue(s) carry acceptance criteria and are not in the baseline; scripts/check-bead-acceptance.sh --update-baseline writes tests/quality/bead-acceptance-baseline.txt, a tracked file to stage in the commit that created the bead"
  fi

  for id in "${absent[@]}"; do
    printf '  NOT IN THE TRACKER  %s\n' "$id"
  done
  for id in "${lost[@]}"; do
    printf '  NO ACCEPTANCE  %s (%s) %s\n' "$id" "${status_of[$id]}" "${title_of[$id]}"
  done

  if [ "$known_count" -eq 0 ]; then
    echo "$gate: $total issue(s), no baseline entries, so no acceptance criteria are protected yet"
    [ -n "$hint" ] && echo "$hint"
    return 0
  fi

  if [ "${#lost[@]}" -eq 0 ] && [ "${#absent[@]}" -eq 0 ]; then
    echo "$gate: $total issue(s), $known_count with acceptance criteria to keep, all present and intact"
    [ -n "$hint" ] && echo "$hint"
    return 0
  fi

  if [ "${#lost[@]}" -gt 0 ]; then
    echo "$gate: ${#lost[@]} issue(s) lost the acceptance criteria the baseline says they have."
  fi
  if [ "${#absent[@]}" -gt 0 ]; then
    echo "$gate: ${#absent[@]} baselined issue(s) are not in the list this run read, so nothing about them was checked."
  fi
  if [ "${#lost[@]}" -gt 0 ] && [ "$text_count" -eq 0 ]; then
    echo "$gate: no issue in this list carries acceptance criteria, so the field is"
    echo "missing from the tracker output rather than from these beads alone. bd omits"
    echo "an empty field, so read the list again before believing this verdict."
  fi
  if [ "${#lost[@]}" -gt 0 ]; then
    echo "An empty acceptance is what 'bd update <id> --acceptance \"\"' writes, and a"
    echo "substitution that produced nothing writes the same thing, both exiting 0."
    echo "Unlike --description, --acceptance has no stdin form, so nothing in bd"
    echo "refuses an empty value: read the criteria back before committing. The text"
    echo "before a wipe is in 'bd history <id> --events', under Old:. Write it back"
    echo "with --acceptance, which is the only write path the flag offers:"
    echo "  bd update <id> --acceptance 'text from bd history'"
  fi
  if [ "${#absent[@]}" -gt 0 ] && [ "${#lost[@]}" -eq 0 ]; then
    echo "A baselined id the list does not carry is not a pass: read it with"
    echo "'bd show <id>', and --update-baseline when the id in the baseline is wrong."
  fi
  return 1
}

# bead_acceptance_verify_missing <issues-json> <baseline> <gate>
#   0 when every live issue carries acceptance criteria or is recorded in the
#   baseline as one that has none, 1 when a live issue has none and nothing
#   records it, printing which.
bead_acceptance_verify_missing() {
  local issues=$1 baseline=$2 gate=$3
  local total

  if ! total=$(jq -r 'if type == "array" then length else error("not an array") end' "$issues" 2>/dev/null); then
    echo "$gate: $issues is not a JSON array of issues, so nothing was read"
    return 1
  fi

  local -A known=() seen=()
  local line
  if [ -f "$baseline" ]; then
    while IFS= read -r line; do
      case "$line" in '' | '#'*) continue ;; esac
      known["$line"]=1
    done <"$baseline"
  fi

  local -a without=()
  mapfile -t without < <(bead_acceptance_without_text "$issues")

  local new=0 stale=0 id status title
  for line in "${without[@]}"; do
    [ -n "$line" ] || continue
    IFS=$'\t' read -r id status title <<<"$line"
    seen["$id"]=1
    if [ -n "${known[$id]:-}" ]; then
      [ "${BEAD_ACCEPTANCE_VERBOSE:-0}" -eq 1 ] && printf '  recorded  %s\n' "$id"
      continue
    fi
    new=$((new + 1))
    printf '  NO CRITERIA  %s (%s) %s\n' "$id" "$status" "$title"
  done

  for id in "${!known[@]}"; do
    [ -z "${seen[$id]:-}" ] || continue
    stale=$((stale + 1))
    [ "${BEAD_ACCEPTANCE_VERBOSE:-0}" -eq 1 ] && printf '  stale  %s\n' "$id"
  done

  # A recorded bead that gained criteria, closed, or left the tracker is an
  # entry the generator would not write now. Reported rather than failed: the
  # protected baseline is what holds that bead's text from here on.
  # The path is printed relative to the tree when it is inside it: a worker reads
  # the gate's line to know which tracked file to stage, and an absolute path
  # under a worktree is the same file with the checkout's name in front of it.
  local shown=$baseline
  if [ -n "${ROOT_DIR:-}" ]; then
    shown=${baseline#"$ROOT_DIR"/}
  fi
  local stale_hint=""
  if [ "$stale" -gt 0 ]; then
    stale_hint="$gate: $stale recorded issue(s) are stale - they carry criteria now, are closed, or are gone; scripts/check-bead-acceptance.sh --update-baseline drops them from $shown"
  fi

  if [ "$new" -eq 0 ]; then
    if [ "${#without[@]}" -eq 0 ]; then
      echo "$gate: $total issue(s), every live one carrying acceptance criteria"
    else
      echo "$gate: ${#without[@]} live issue(s) have no acceptance criteria, all recorded in $shown"
    fi
    [ -n "$stale_hint" ] && echo "$stale_hint"
    return 0
  fi

  echo "$gate: $new live issue(s) carry no acceptance criteria, and no baseline records them."
  echo "A bead written without them leaves the worker, and the review after it,"
  echo "nothing to check done against: the worker plans from the description, and"
  echo "this gate cannot tell that bead from one whose criteria were wiped, because"
  echo "bd writes no key for an empty field. Write them, through the one write path"
  echo "--acceptance has:"
  echo "  bd update <id> --acceptance 'what done looks like'"
  echo "A bead meant to stay without them is recorded deliberately by the update"
  echo "that writes both baselines:"
  echo "  scripts/check-bead-acceptance.sh --update-baseline"
  echo "$shown is a tracked file to stage in the commit that created the bead."
  [ -n "$stale_hint" ] && echo "$stale_hint"
  return 1
}
