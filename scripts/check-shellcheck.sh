#!/usr/bin/env bash
#
# check-shellcheck.sh - lint every committed shell file with shellcheck.
#
# Usage:
#   scripts/check-shellcheck.sh                 # check against the baseline
#   scripts/check-shellcheck.sh -v|--verbose    # also list the known findings
#   scripts/check-shellcheck.sh --update-baseline
#
# The shell scripts are the gates and the test harnesses, so a defect in one of
# them is a gate that reports the wrong answer. A reviewer linted three of them
# once, by hand, found SC1091 on the source pattern every script here uses, and
# lost its commit step to the non-zero exit. Nothing ran it again.
#
# Two things about the invocation are load bearing:
#
#   - Every file is checked with -P <its own directory>. shellcheck resolves a
#     relative '# shellcheck source=...' against the caller's working
#     directory, not the file's, so one invocation over a list from the tree root
#     reports SC1091 on every script that sources scripts/lib/ and -x follows
#     nothing. With -P the sourced file resolves and is checked too.
#   - The version is the one in the dev shell. Findings appear and disappear
#     between releases, so a baseline generated by a shellcheck the gate does not
#     run reports findings that are not new. flake.nix pins it with the rest of
#     the dev shell.
#
# The baseline lives in tests/quality/shellcheck-baseline.txt and records each
# finding with its occurrence count. scripts/lib/shellcheck-report.sh does the
# judging, including the refusal to call an empty log a clean run.
#
# Exit status: 0 when the baseline records every finding, 1 otherwise.

set -uo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR" || exit 1

BASELINE_FILE="$ROOT_DIR/tests/quality/shellcheck-baseline.txt"
VERBOSE=0
UPDATE=0

for arg in "$@"; do
  case "$arg" in
    -v | --verbose) VERBOSE=1 ;;
    --update-baseline) UPDATE=1 ;;
    -h | --help)
      awk 'NR > 1 { if (!/^#/) exit; sub(/^# ?/, ""); print }' "$0"
      exit 0
      ;;
    *)
      echo "check-shellcheck: unknown argument '$arg'" >&2
      exit 1
      ;;
  esac
done

if ! command -v shellcheck >/dev/null 2>&1; then
  echo "check-shellcheck: shellcheck not found; start the dev shell (direnv allow)" >&2
  exit 1
fi

# A shell file is anything with a shell shebang: the gates under scripts/, the
# seam harness under tests/x/, the hook trampolines in .githooks/ and .envrc.
# The .sh extension alone would miss the last two, and they run on every commit.
# Untracked files are included so a script is linted before it is staged: a
# file list built from the index alone says the tree is clean while the file the
# next commit adds has never been read.
SHELL_FILES=()
while IFS= read -r f; do
  [ -f "$f" ] || continue
  case "$(head -n 1 "$f" 2>/dev/null)" in
    '#!'*sh*) SHELL_FILES+=("$f") ;;
  esac
done < <(git ls-files --cached --others --exclude-standard | grep -v '^vendor/')

if [ "${#SHELL_FILES[@]}" -eq 0 ]; then
  echo "check-shellcheck: no shell files found; is this the repository root?" >&2
  exit 1
fi

LOG="${TMPDIR:-/tmp}/wm-shellcheck.log"
: >"$LOG"
for f in "${SHELL_FILES[@]}"; do
  shellcheck -x -P "$(dirname "$f")" -f gcc "$f" >>"$LOG" 2>&1
done

# shellcheck source=lib/shellcheck-report.sh
. "$ROOT_DIR/scripts/lib/shellcheck-report.sh"

if [ "$UPDATE" -eq 1 ]; then
  mapfile -t ENTRIES < <(lint_report_findings "$LOG")
  lint_write_baseline "$BASELINE_FILE" "scripts/check-shellcheck.sh --update-baseline" "${ENTRIES[@]}"
  echo "check-shellcheck: baseline updated with ${#ENTRIES[@]} entrie(s) in ${BASELINE_FILE#"$ROOT_DIR/"}"
  exit 0
fi

SHELLCHECK_VERBOSE=$VERBOSE
export SHELLCHECK_VERBOSE
lint_verify "$LOG" "$BASELINE_FILE" check-shellcheck || exit 1
echo "check-shellcheck: ${#SHELL_FILES[@]} file(s) linted, no finding outside the baseline"
