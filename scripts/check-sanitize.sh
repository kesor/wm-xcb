#!/usr/bin/env bash
#
# check-sanitize.sh - fail on a memory leak that is not already known.
#
# Usage: scripts/check-sanitize.sh [--update-baseline] [--verbose]
#
# The unit suite runs under AddressSanitizer and UndefinedBehaviorSanitizer.
# Leaks are reported with the allocation site: the first stack frame that is one
# of this repository's files. A site listed in tests/quality/asan-baseline.txt is
# known debt; a site that is not listed fails the check.
#
# Why a baseline rather than a clean run: the tag-manager and tiling test groups
# only started running recently, and they leaked machines the monitor never
# destroyed. A gate that is red for reasons nobody is fixing today teaches people
# to ignore it. The baseline makes the number go down and nothing else.
#
# Exit status: 0 when there is no new leak site, 1 otherwise.

set -uo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

BASELINE="$ROOT_DIR/tests/quality/asan-baseline.txt"
UPDATE=0
VERBOSE=0
for arg in "$@"; do
  case "$arg" in
    --update-baseline) UPDATE=1 ;;
    -v | --verbose) VERBOSE=1 ;;
    -h | --help)
      sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "check-sanitize: unknown argument '$arg'" >&2
      exit 1
      ;;
  esac
done

LOG=$(mktemp)
trap 'rm -f "$LOG"' EXIT

echo "check-sanitize: building with SANITIZE=1 and running the suite"
make clean >/dev/null 2>&1
# A leak report makes the test binary exit non-zero, which is not the same thing
# as a failed assertion: parse the summary and decide from that.
make SANITIZE=1 test >"$LOG" 2>&1 || true
if ! grep -qE 'Total: [0-9]+ passed, 0 failed' "$LOG"; then
  grep -E "error:" "$LOG" | head -20 >&2
  echo "check-sanitize: the tree does not build or the suite failed; see below" >&2
  tail -30 "$LOG" >&2
  exit 1
fi

# Allocation sites: the first frame that names a file in this repository, keyed
# by file and function. The line number is not part of the key on purpose: it
# moves with any edit above it, and inlining changes which frame ASan reports
# between two builds of the same source, so a line-keyed baseline goes stale for
# no reason. A function rename should leave a stale entry behind, which is the
# signal you want.
mapfile -t SITES < <(
  grep -A6 'Direct leak' "$LOG" |
    grep -oE 'in [A-Za-z_0-9]+ [a-z0-9_/.-]+\.(c|h):[0-9]+' |
    sed -E 's/^in ([A-Za-z_0-9]+) (.*):[0-9]+$/\2|\1/' |
    sed "s|^$ROOT_DIR/||" |
    sort -u
)
if [ "${#SITES[@]}" -eq 0 ]; then
  echo "check-sanitize: no leaks at all"
  exit 0
fi

if [ "$UPDATE" -eq 1 ]; then
  mkdir -p "$(dirname "$BASELINE")"
  {
    echo "# Allocation sites with a known leak under AddressSanitizer."
    echo "#"
    echo "# Generated by scripts/check-sanitize.sh --update-baseline."
    echo "# A site listed here does not fail the check; a site missing from here"
    echo "# does. Remove entries as the leaks are fixed: the list is meant to shrink."
    printf '%s\n' "${SITES[@]}"
  } >"$BASELINE"
  echo "check-sanitize: baseline updated with ${#SITES[@]} site(s)"
  exit 0
fi

declare -A KNOWN=()
if [ -f "$BASELINE" ]; then
  while IFS= read -r line; do
    case "$line" in '' | '#'*) continue ;; esac
    KNOWN["$line"]=1
  done <"$BASELINE"
fi

NEW=0
declare -A SEEN=()
for site in "${SITES[@]}"; do
  SEEN["$site"]=1
  if [ -n "${KNOWN[$site]:-}" ]; then
    [ "$VERBOSE" -eq 1 ] && printf '  known  %s\n' "$site"
    continue
  fi
  NEW=$((NEW + 1))
  printf '  NEW LEAK  %s\n' "$site"
done

STALE=0
for site in "${!KNOWN[@]}"; do
  [ -z "${SEEN[$site]:-}" ] && STALE=$((STALE + 1)) && printf '  stale baseline entry: %s\n' "$site"
done

SUMMARY=$(grep -oE 'SUMMARY: AddressSanitizer: [0-9]+ byte\(s\) leaked in [0-9]+ allocation\(s\)' "$LOG" | tail -1)
[ -n "$SUMMARY" ] && echo "check-sanitize: $SUMMARY"
echo "check-sanitize: ${#SITES[@]} site(s), $NEW new"
[ "$STALE" -gt 0 ] && echo "check-sanitize: $STALE stale baseline entrie(s); run --update-baseline to drop them"

if [ "$NEW" -gt 0 ]; then
  echo "A new leak site: fix it, or run --update-baseline and say why it is deferred."
  exit 1
fi
exit 0
