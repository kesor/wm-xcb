#!/usr/bin/env bash
# scripts/check-sanitize.sh judged a run it never checked: an uninstrumented
# tree, or a suppression file, left a log with no report in it, and the script
# printed "no leaks at all" and exited 0. The verdict is shared with the
# nested-server gate now, in scripts/lib/sanitize-report.sh, so this feeds it
# recorded output in the shape gcc actually writes it, instead of starting a
# suite under the sanitizers.
#
# The shape matters: a frame for a file named with a directory is printed as that
# relative path, and one for a file named without is printed under the compiler's
# working directory. A key that accepts only the second form misses every leak
# below the tree root.
source "$(dirname "$0")/lib.sh"
# shellcheck source=../../scripts/lib/sanitize-report.sh
. "$ROOT_DIR/scripts/lib/sanitize-report.sh"

DIR="$TMPDIR_SEAM/sanitize-report"
rm -rf "$DIR"
mkdir -p "$DIR"

# The frames below are copied from a real `make SANITIZE=1 test` log: a leak
# that starts in a subdirectory file, with root-level frames mixed in.
UNIT_LOG="$DIR/unit.log"
cat >"$UNIT_LOG" <<EOF
  [PASS] 64 passed, 0 failed

  Total: 823 passed, 0 failed

Direct leak of 32 byte(s) in 1 object(s) allocated from:
    #0 0x7ffff792b31f in realloc.part.0 (/nix/store/libasan.so.8+0x12b31f)
    #1 0x5555556073b8 in monitor_sm_set_internal src/target/monitor.c:109
    #2 0x5555556073b8 in monitor_set_sm src/target/monitor.c:560
    #3 0x5555555f7654 in hub_unadopt_components_for_target $ROOT_DIR/wm-hub.c:538

Indirect leak of 120 byte(s) in 1 object(s) allocated from:
    #0 0x7ffff792c01f in malloc (/nix/store/libasan.so.8+0x12c01f)
    #1 0x555555603605 in client_create src/target/client.c:310
    #2 0x5555555e5778 in test_client_tag_move_triggers_tiling tests/unit/test-tiling-component.c:313
    #3 0x5555555c0b18 in main $ROOT_DIR/tests/unit/test-registry.c:100

Direct leak of 8 byte(s) in 1 object(s) allocated from:
    #0 0x7ffff792c01f in malloc (/nix/store/libasan.so.8+0x12c01f)
    #1 0x5555555a23c2 in setup_ewmh $ROOT_DIR/wm-xcb-ewmh.c:19
    #2 0x55555559ba30 in main $ROOT_DIR/wm.c:23

SUMMARY: AddressSanitizer: 160 byte(s) leaked in 3 allocation(s).
EOF

mapfile -t SITES < <(sanitize_report_sites "$UNIT_LOG")
check_eq "a subdirectory frame keys to its path in the tree" 1 \
  "$(printf '%s\n' "${SITES[@]}" | grep -c '^src/target/monitor.c|monitor_sm_set_internal$')"
check_eq "an Indirect leak has a site too" 1 \
  "$(printf '%s\n' "${SITES[@]}" | grep -c '^src/target/client.c|client_create$')"
check_eq "a file named without a directory keys under the tree root" 1 \
  "$(printf '%s\n' "${SITES[@]}" | grep -c '^wm-xcb-ewmh.c|setup_ewmh$')"
check_eq "a frame in a library outside the tree is not a site" 0 \
  "$(printf '%s\n' "${SITES[@]}" | grep -c 'libasan')"
check_eq "the allocation site, not every frame above it, is the key" 0 \
  "$(printf '%s\n' "${SITES[@]}" | grep -c '^wm-hub.c|hub_unadopt_components_for_target$')"

BASELINE="$DIR/baseline.txt"
CLEAN_LOG="$DIR/clean.log"
cat >"$CLEAN_LOG" <<EOF
  [PASS] 64 passed, 0 failed

  Total: 823 passed, 0 failed
EOF

LAST="$DIR/last.txt"

# A log with nothing in it says nothing. With a baseline to match against, that
# is either the fixes landing without their baseline update or a sanitizer that
# never ran, and the gate refuses to guess.
{
  echo "# A known site."
  echo "src/target/monitor.c|monitor_sm_set_internal"
} >"$BASELINE"
sanitize_verify_sites "$CLEAN_LOG" "$BASELINE" check-sanitize >"$LAST" 2>&1
check_eq "a clean log next to a baseline entry fails" 1 "$?"
check_eq "the refusal is the unit gate's" 1 "$(grep -c 'check-sanitize: the log carries no sanitizer report' "$LAST")"
check_eq "the refusal names the baseline" 1 "$(grep -c 'lists 1 site' "$LAST")"

# The report the run did produce decides, and the keys the two gates share are
# what it is matched on.
sanitize_verify_sites "$UNIT_LOG" "$BASELINE" check-sanitize >"$LAST" 2>&1
check_eq "an unlisted site fails" 1 "$?"
check_eq "the unlisted subdirectory site is named" 1 "$(grep -c 'NEW REPORT  src/target/client.c|client_create' "$LAST")"
check_eq "the listed site is not reported as new" 0 "$(grep -c 'NEW REPORT  src/target/monitor.c' "$LAST")"

# A baseline written from a run round-trips: the same log against it is clean.
mapfile -t WRITTEN < <(sanitize_report_sites "$UNIT_LOG")
sanitize_write_baseline "$BASELINE" "a test" "${WRITTEN[@]}"
check_eq "the generator is recorded in the baseline header" 1 "$(grep -c '^# Generated by a test\.$' "$BASELINE")"
sanitize_verify_sites "$UNIT_LOG" "$BASELINE" check-sanitize >"$LAST" 2>&1
check_eq "a baseline written from the run accepts that run" 0 "$?"

# An empty baseline and a clean log is the one case with nothing to judge.
echo "# Nothing known." >"$BASELINE"
sanitize_verify_sites "$CLEAN_LOG" "$BASELINE" check-sanitize >"$LAST" 2>&1
check_eq "a clean log next to an empty baseline passes" 0 "$?"
# The success line says which case it accepted. "no sanitizer report at all"
# was the wording of both refusals too, so a clean run read as a gate admitting
# it had checked nothing.
check_eq "and says what it accepted" 1 \
  "$(grep -c 'no sanitizer report, and the baseline is empty: nothing to check' "$LAST")"

finish
