#!/usr/bin/env bash
# A lint that found nothing and a lint that never ran print the same thing, and
# a finding that moved is not a finding that was fixed. scripts/lib/shellcheck-report.sh
# decides between those cases for scripts/check-shellcheck.sh; this feeds it
# recorded output instead of running shellcheck, so each refusal is pinned where
# a reader can see what it is for.
source "$(dirname "$0")/lib.sh"
# shellcheck source=../../scripts/lib/shellcheck-report.sh
. "$ROOT_DIR/scripts/lib/shellcheck-report.sh"

DIR="$TMPDIR_SEAM/shellcheck-report"
rm -rf "$DIR"
mkdir -p "$DIR"

LOG="$DIR/shellcheck.log"
BASELINE="$DIR/baseline.txt"
LAST="$DIR/last.txt"

CD_FINDING="scripts/one.sh:12:1: warning: Use 'cd ... || exit' or 'cd ... || return' in case cd fails. [SC2164]"
UNUSED_FINDING="scripts/two.sh:7:3: warning: unused appears unused. Verify use (or export if used externally). [SC2034]"

cat >"$LOG" <<EOF
$CD_FINDING
$UNUSED_FINDING
EOF

mapfile -t FINDINGS < <(lint_report_findings "$LOG")
check_eq "one finding keys to file, code and message, with a count" 1 \
  "$(printf '%s\n' "${FINDINGS[@]}" | grep -cF "scripts/one.sh|SC2164|Use 'cd ... || exit' or 'cd ... || return' in case cd fails.|1")"

# The line number is not part of the key, so the same finding at two lines in
# one file is one entry with a count. Dropping the count would hide the second
# one behind a baseline written for the first.
cat >"$LOG" <<EOF
$CD_FINDING
scripts/one.sh:40:1: warning: Use 'cd ... || exit' or 'cd ... || return' in case cd fails. [SC2164]
EOF
check_eq "the same finding twice in one file is one entry with a count of two" 1 \
  "$(lint_report_findings "$LOG" | grep -cF "scripts/one.sh|SC2164|Use 'cd ... || exit' or 'cd ... || return' in case cd fails.|2")"

mapfile -t ENTRIES < <(lint_report_findings "$LOG")
lint_write_baseline "$BASELINE" "a test" "${ENTRIES[@]}"
check_eq "the generator is recorded in the baseline header" 1 \
  "$(grep -c '^# Generated by a test\.$' "$BASELINE")"
lint_verify "$LOG" "$BASELINE" check-shellcheck >"$LAST" 2>&1
check_eq "a baseline written from the run accepts that run" 0 "$?"
check_eq "and the summary counts the findings" 1 "$(grep -c '2 finding(s), 0 new, 2 known' "$LAST")"

cat >"$LOG" <<EOF
$CD_FINDING
scripts/one.sh:40:1: warning: Use 'cd ... || exit' or 'cd ... || return' in case cd fails. [SC2164]
scripts/one.sh:60:1: warning: Use 'cd ... || exit' or 'cd ... || return' in case cd fails. [SC2164]
EOF
lint_verify "$LOG" "$BASELINE" check-shellcheck >"$LAST" 2>&1
check_eq "an extra occurrence of an entry the baseline already has fails" 1 "$?"
check_eq "the entry it belongs to is named" 1 "$(grep -c 'NEW FINDING  scripts/one.sh|SC2164' "$LAST")"

cat >"$LOG" <<EOF
$CD_FINDING
EOF
lint_verify "$LOG" "$BASELINE" check-shellcheck >"$LAST" 2>&1
check_eq "a finding that went away passes" 0 "$?"
check_eq "and its baseline entry is reported as shrunk" 1 "$(grep -c 'baseline entry can shrink' "$LAST")"

: >"$LOG"
lint_verify "$LOG" "$BASELINE" check-shellcheck >"$LAST" 2>&1
check_eq "an empty log next to a baseline entry fails" 1 "$?"
check_eq "the refusal says the log cannot tell the two apart" 1 "$(grep -c 'fails rather than guess' "$LAST")"

cat >"$LOG" <<EOF
$CD_FINDING
shellcheck: scripts/one.sh: getDirectoryContents: does not exist
EOF
lint_verify "$LOG" "$BASELINE" check-shellcheck >"$LAST" 2>&1
check_eq "a log line that is not a finding fails" 1 "$?"
check_eq "the unparsed line is shown" 1 "$(grep -c 'not a finding: shellcheck:' "$LAST")"

printf '# Nothing known.\n' >"$BASELINE"
: >"$LOG"
lint_verify "$LOG" "$BASELINE" check-shellcheck >"$LAST" 2>&1
check_eq "an empty log next to an empty baseline passes" 0 "$?"
check_eq "and says there was nothing to judge" 1 "$(grep -c 'no finding at all' "$LAST")"

finish
